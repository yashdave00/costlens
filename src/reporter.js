const SEV_ORDER = ["critical", "high", "medium", "low", "info"];
const SEV_EMOJI = { critical: "🔴", high: "🟠", medium: "🟡", low: "🔵", info: "⚪" };

export function renderReport(result) {
  const { root, fileCount, findings, summary } = result;
  const lines = [];
  lines.push(`# CostLens Report`);
  lines.push("");
  lines.push(`**Project:** \`${root}\``);
  lines.push(`**Files scanned:** ${fileCount}`);
  lines.push(`**Findings:** ${findings.length}  (${SEV_ORDER.map((s) => `${s}: ${summary[s] || 0}`).join(", ")})`);
  lines.push("");

  if (findings.length === 0) {
    lines.push("No cost leaks detected. Nice.");
    return lines.join("\n");
  }

  // Group by severity
  for (const sev of SEV_ORDER) {
    const group = findings.filter((f) => f.severity === sev);
    if (group.length === 0) continue;
    lines.push(`## ${SEV_EMOJI[sev]} ${sev.toUpperCase()} (${group.length})`);
    lines.push("");
    for (const f of group) {
      lines.push(`### ${f.title}`);
      lines.push("");
      lines.push(f.detail);
      lines.push("");
      if (f.savings) lines.push(`**Estimated impact:** ${f.savings}`);
      if (f.files && f.files.length > 0) {
        lines.push("");
        lines.push("**Locations:**");
        for (const loc of f.files.slice(0, 20)) {
          lines.push(`- \`${loc.path}\`${loc.line ? `:${loc.line}` : ""}`);
        }
      }
      if (f.fixPrompt) {
        lines.push("");
        lines.push("**Fix prompt (paste into Claude Code / Cursor):**");
        lines.push("```");
        lines.push(f.fixPrompt);
        lines.push("```");
      }
      lines.push("");
      lines.push("---");
      lines.push("");
    }
  }

  // Combined fix prompt at the end for agent consumption
  lines.push("## 🤖 Agent Fix Block (paste entire block into your coding agent)");
  lines.push("");
  lines.push("```");
  lines.push("You are a senior engineer optimizing this codebase for cloud/infra cost. Apply the following fixes, smallest safe change first, and run the build/tests after each group:");
  lines.push("");
  for (const f of findings) {
    if (f.fixPrompt) lines.push("- " + f.fixPrompt);
  }
  lines.push("```");
  lines.push("");
  lines.push("_Generated by CostLens. Re-run after fixes to verify._");

  return lines.join("\n");
}
